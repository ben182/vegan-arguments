// Site-wide constants shared by the app, the server routes and the Nuxt config.
import type { Texts } from "./texts";

export const DEFAULT_SITE_URL = "https://vegan-arguments.pages.dev";

/** Production address for canonical links and the sitemap, from SITE_URL, without trailing slash. */
export const resolveSiteUrl = (env: string | undefined) => (env || DEFAULT_SITE_URL).replace(/\/$/, "");

export const THEME_COLOR = "#2b1a2c";
export const BACKGROUND_COLOR = "#f5f3f4";

export const REPO_URL = "https://github.com/ben182/vegan-arguments";

const ICONS = [
  { src: "/pwa-64x64.png", sizes: "64x64", type: "image/png" },
  { src: "/pwa-192x192.png", sizes: "192x192", type: "image/png" },
  { src: "/pwa-512x512.png", sizes: "512x512", type: "image/png" },
  { src: "/maskable-icon-512x512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
];

/** Web app manifest per language (name, start page). */
export const webManifest = (t: Texts) => ({
  name: t.title,
  short_name: t.brand,
  description: t.description,
  lang: t.lang,
  start_url: t.homePath,
  scope: "/",
  display: "standalone" as const,
  theme_color: THEME_COLOR,
  background_color: BACKGROUND_COLOR,
  icons: ICONS,
});

/** Path of the manifest for a language: the German one is generated by @vite-pwa/nuxt. */
export const webManifestPath = (lang: string) => (lang === "de" ? "/manifest.webmanifest" : `/manifest.${lang}.webmanifest`);
